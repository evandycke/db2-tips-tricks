SELECT 
	'DHB_PRD' AS BDD_CIBLE,
	'RAW_IKO' AS SCHEMA_CIBLE,
	TABLE_NAME AS TABLE_CIBLE, 
	COLUMN_NAME AS COLONNE_CIBLE,
	DATA_TYPE AS TYPE_DONNEE_CIBLE,
	CASE WHEN IS_NULLABLE = 'N' THEN 'Non' ELSE 'Oui' END AS NULLABLE,
	LENGTH AS LONGUEUR,
	COLUMN_TEXT AS DESCRIPTION
FROM QSYS2.SYSCOLUMNS
WHERE (1=1)
AND TABLE_SCHEMA = 'IKGLFIC'
AND TABLE_NAME = 'CNCGENP'
ORDER BY ORDINAL_POSITION
LIMIT 100